USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS ECOMMERCE_DBT;

-- Włączenie roli projektu do hierarchii administracyjnej
GRANT ROLE ECOMMERCE_DBT TO ROLE SYSADMIN;

-- Dostęp do zasobów obliczeniowych i bazy
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH
    TO ROLE ECOMMERCE_DBT;

GRANT USAGE ON DATABASE ECOMMERCE
    TO ROLE ECOMMERCE_DBT;

-- RAW: dbt seed będzie tworzyć i wypełniać tabele
GRANT USAGE, CREATE TABLE ON SCHEMA ECOMMERCE.RAW
    TO ROLE ECOMMERCE_DBT;

-- STAGING i MARTS: dbt będzie tworzyć tabele i widoki
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE.STAGING
    TO ROLE ECOMMERCE_DBT;

GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ECOMMERCE.MARTS
    TO ROLE ECOMMERCE_DBT;

SELECT CURRENT_USER();
GRANT ROLE ECOMMERCE_DBT TO USER SOSZE;

